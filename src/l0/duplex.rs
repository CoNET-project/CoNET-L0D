pub fn parse_duplex_frame_json(payload: &str) -> Option<(String, String)> {
    let v: Value = serde_json::from_str(payload.trim()).ok()?;
    if v.get("type").and_then(Value::as_str) != Some("duplex_frame") {
        return None;
    }
    let session_id = v.get("pipe_handle")?.as_str()?.to_string();
    let b64 = v.get("payload")?.as_str()?.to_string();
    Some((session_id, b64))
}

pub fn parse_duplex_ping_json(payload: &str) -> Option<String> {
    let v: Value = serde_json::from_str(payload.trim()).ok()?;
    if v.get("type").and_then(Value::as_str) != Some("duplex_ping") {
        return None;
    }
    v.get("pipe_handle")?.as_str().map(str::to_string)
}

